'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const html=read('src/renderer/index.html'),css=read('src/renderer/apex5-green-reference-v3.css');
const ui=read('src/renderer/apex5-green-reference-v3.js'),app=read('src/renderer/app.js');
const pkg=JSON.parse(read('package.json')),main=read('src/main.js');
test('approved green/slate look is a new full-width inventory layout, not Preview 2 side rail',()=>{
 assert.match(html,/class="hidden ap5-v2-inventory ap5-v3-inventory"/);
 const content=html.slice(html.indexOf('id="inventoryPage"'),html.indexOf('id="scanPage"'));
 assert.doesNotMatch(content,/ap5-v2-register-rail|ap5-v2-register-layout/);
 assert.match(content,/ap5-v3-register-main/);
 assert.match(content,/ap5-v3-filters" id="ap5V3Filters"/);
 assert.match(content,/ap5-v3-filter-actions" id="ap5V3FilterActions"/);
 assert.match(content,/id="ap5V3Sync"/);
 assert.match(content,/id="invAdd" class="primary">＋ Add device/);
 assert.match(css,/#appPage \.sidebar\{background:linear-gradient/);
 assert.match(css,/#appPage \.menu-item\.active\{background:#0d2435/);
 assert.match(css,/#appPage \.ap5-v3-register-main #inventoryQuickFilters/);
 assert.match(css,/#appPage \.ap5-v3-filters\{order:1/);
 assert.match(css, /#appPage #inventoryTable \.ap5-v3-asset-table/);
 assert.match(css, /overflow-x:hidden!important/);
});
test('Brand and device-type filters are real interactive filters in existing register rendering',()=>{
 assert.match(ui,/createSelect\('ap5V3TypeFilter','Device type'\)/);
 assert.match(ui,/createSelect\('ap5V3BrandFilter','Brand'\)/);
 assert.match(app,/document\.getElementById\('ap5V3BrandFilter'\)\?\.value/);
 assert.match(app,/document\.getElementById\('ap5V3TypeFilter'\)\?\.value/);
 assert.match(ui,/sel\.addEventListener\('change'/);
 assert.match(ui,/inventoryPageIndex=0;render\(\)/);
 for(const id of ['statusFilter','locationFilter','inventorySearch'])assert(ui.includes("moveControl('"+id+"'")||ui.includes("byId('"+id+"')"),id);
 assert.match(ui,/search\.placeholder='Search by asset ID, serial number, model…'/);
});
test('Existing inventory statuses, actions and selection remain mounted in new screen',()=>{
 for(const id of ['inventoryTable','inventorySearch','invAdd','invScan','assetEditor','topTheme'])assert(html.includes('id="'+id+'"'),id);
 for(const v of ['inventoryQuickFilters','inventoryActiveFilters','selection-toolbar-inventory','data-asset','condition-pill','inventoryTable'])assert(ui.includes(v),v);
 assert.match(ui,/identity\.replaceChildren\(idButton\)/);
 assert.match(ui,/identity\.after\(deviceCell,serialCell\)/);
 assert.match(ui,/const prior=render;\s*render=function\(\.\.\.args\)/);
 assert.match(ui,/exportButton\.onclick=\(\)=>byId\('settingsExport'\)\?\.click\(\)/);
 assert.match(ui,/sync\.onclick=async\(\)=>/);
 assert.match(ui,/await refresh\(\)/);
 assert.match(ui,/data-ap5-v3-view/);
 assert.match(ui,/setPage\('refurbWorkspace'\)/);
 assert.match(ui,/data-rw-view/);
 assert.doesNotMatch(ui,/api\.update\(|api\.remove\(|api\.add\(|fetch\(/);
});
test('New columns fit without a forced sideways scrollbar and use grounded inventory records',()=>{
 const cols=[3.3,8,18,12,12,8,10,16,8,4.7];
 assert(Math.abs(cols.reduce((a,b)=>a+b,0)-100)<0.001);
 for(let i=0;i<cols.length;i++)assert(css.includes('>thead>tr>th:nth-child('+(i+1)+'){width:'+cols[i]+'%!important}'),'Column '+(i+1));
 assert.match(ui,/record=items\.find\(a=>String\(a\.id\)/);
 assert.match(ui,/identity\.querySelector\('\.apex-device-serial'\)/);
 assert.match(ui,/record\?\.manufacturer/);
 assert.match(css,/@media\(max-width:1260px\)/);
 assert.match(css,/@media\(max-width:950px\)/);
});
test('Preview 3 remains a separate offline demo app with no production cloud or hub access',()=>{
 assert.equal(pkg.version,'5.0.0-preview.3');
 assert.equal(pkg.build.appId,'com.apex.management.preview5');
 assert.equal(pkg.build.productName,'APEX Management Studio 5 Preview');
 assert.equal(pkg.build.publish,undefined);
 assert(!pkg.build.files.some(x=>x.startsWith('cloud/')||x.startsWith('hub/')));
 assert.match(main,/app\.setPath\('userData',previewUserData\)/);
 assert.match(main,/globalThis\.fetch=async\(\)=>\{throw Error\('Network disabled:/);
 assert.match(main,/callback\(\{cancel:true\}\)/);
 assert.deepEqual(JSON.parse(read('src/cloud-login-distribution.json')),{});
 assert.match(html,/APEX 5\.0 Green Professional Preview 3 — Offline Demo/);
 assert.match(html,/href="apex5-green-reference-v3\.css"/);
 assert.match(html,/src="apex5-green-reference-v3\.js"/);
});
